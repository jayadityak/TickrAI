"""AI Chat with Report — lets users ask follow-up questions about a company.

The full report data (all 7 agent outputs) is injected as context so GPT
answers are grounded in real financials, not hallucinated.
"""

import json
import logging
from typing import AsyncGenerator

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from openai import AsyncOpenAI

from ..config import settings
from ..utils.auth import get_current_user

logger = logging.getLogger(__name__)

router = APIRouter()

SYSTEM_PROMPT = """You are an expert equity research analyst assistant for TickrAI, an AI-powered stock research platform.

You have access to a comprehensive research report for {ticker} ({company_name}). The report was generated by 7 specialized research agents covering:
1. Company Overview — business description, products, competitive position
2. Financial Analysis — revenue, margins, EPS, key metrics
3. Risk Analysis — leverage, liquidity, cash flow, regulatory risks
4. Auditor Flags — earnings quality, going-concern signals
5. Earnings Call Insights — management tone, guidance, analyst concerns
6. Sector & Peer Comparison — peer benchmarks, tailwinds/headwinds
7. Green/Red Flags — bullish and bearish signals with a composite score

Here is the full report data:
{report_data}

Instructions:
- Answer questions using ONLY the data provided in the report above. Do not make up numbers.
- If the report doesn't contain information to answer a question, say so honestly.
- Be concise but insightful. Use specific numbers and data points from the report.
- Format responses with markdown for readability (bold key figures, use bullet points).
- When comparing to peers, reference the actual peer data in the report.
- If asked for an opinion, frame it as "based on the data in the report" not as personal advice.
"""


class ChatRequest(BaseModel):
    message: str
    report_data: dict
    history: list[dict] = []  # [{role: "user"/"assistant", content: "..."}]


@router.post("/api/reports/{ticker}/chat")
async def chat_with_report(
    ticker: str,
    body: ChatRequest,
    user: dict = Depends(get_current_user),
):
    """Stream an AI response to a user question about a report."""
    if not settings.openai_api_key:
        raise HTTPException(status_code=503, detail="OpenAI API key not configured")

    # Extract company name from report data
    company_name = ticker
    for section in body.report_data.values():
        if isinstance(section, dict) and section.get("data"):
            data = section["data"]
            if isinstance(data, dict) and "business_description" in data:
                # Try to get from overview
                company_name = ticker
                break

    # Build the system prompt with report context
    system = SYSTEM_PROMPT.format(
        ticker=ticker.upper(),
        company_name=company_name,
        report_data=json.dumps(body.report_data, indent=2, default=str)[:15000],  # Cap context size
    )

    # Build message history
    messages = [{"role": "system", "content": system}]

    # Add conversation history (last 10 exchanges)
    for msg in body.history[-20:]:
        if msg.get("role") in ("user", "assistant") and msg.get("content"):
            messages.append({"role": msg["role"], "content": msg["content"]})

    # Add current message
    messages.append({"role": "user", "content": body.message})

    client = AsyncOpenAI(api_key=settings.openai_api_key)

    async def generate() -> AsyncGenerator[str, None]:
        try:
            stream = await client.chat.completions.create(
                model=settings.openai_model,
                messages=messages,
                stream=True,
                max_tokens=1000,
                temperature=0.3,
            )
            async for chunk in stream:
                delta = chunk.choices[0].delta
                if delta.content:
                    yield f"data: {json.dumps({'content': delta.content})}\n\n"
            yield f"data: {json.dumps({'done': True})}\n\n"
        except Exception as e:
            logger.exception("Chat error for %s", ticker)
            yield f"data: {json.dumps({'error': str(e)})}\n\n"

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )
